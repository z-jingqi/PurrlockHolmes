"""Pack aligned room repairs and transparent Blender props into one small atlas."""
from pathlib import Path
from PIL import Image, ImageFilter
import json, os
root=Path(__file__).resolve().parents[1]
out=Path(os.environ.get("PURR_PICKUP_DIR","/tmp/purr-pickup"))
clean=Image.open(out/'clean.png').convert('RGBA')
mask=Image.open(root/'assets/pick.png').getchannel('R')
tiles=[]; meta={}
for i in range(1,8):
    visible=mask.point(lambda v:255 if v==i*32 else 0)
    l,t,r,b=visible.getbbox(); m=27
    x0,y0,x1,y1=max(0,l-m),max(0,t-m),min(mask.width,r+m),min(mask.height,b+m)
    patch=clean.crop((x0,y0,x1,y1))
    alpha=Image.new('L',patch.size)
    other=mask.point(lambda v:255 if v and v!=i*32 else 0).filter(ImageFilter.MaxFilter(3))
    alpha.putdata([0 if other.getpixel((x+x0,y+y0)) else round(255*min(1,min(x,y,patch.width-1-x,patch.height-1-y)/13)) for y in range(patch.height) for x in range(patch.width)])
    patch.putalpha(alpha)
    item=Image.open(out/f'item-{i}.png').convert('RGBA')
    box=item.getchannel('A').point(lambda v:255 if v>8 else 0).getbbox()
    assert box and l>=box[0]-2 and r<=box[2]+2,(i,box,(l,t,r,b))
    sprite=item.crop(box)
    meta[str(i)]={'origin':[x0,y0],'center':[(box[0]+box[2])/2,(box[1]+box[3])/2]}
    tiles.extend([(str(i),'patch',patch),(str(i),'sprite',sprite)])
atlas=Image.new('RGBA',(880,760))
x=y=row=0
for i,kind,tile in tiles:
    if x+tile.width+3>atlas.width: x=0; y+=row+3; row=0
    assert y+tile.height<=atlas.height
    atlas.paste(tile,(x,y))
    meta[i][kind]=[x,y,tile.width,tile.height]
    x+=tile.width+3; row=max(row,tile.height)
atlas.crop((0,0,atlas.width,y+row)).save(root/'assets/pickups.webp',quality=91,method=6)
(root/'assets/pickups.json').write_text(json.dumps(meta,separators=(',',':'))+'\n')
(root/'assets/pickup_data.gd').write_text('# Generated by art/pack_pickups.py.\nconst ITEMS := '+json.dumps(meta,separators=(',',':'))+'\n')
