"""Export the approved fitted cat as a lightweight, UV-mapped game mesh.

Usage: blender -b <fitted-cat.blend> -P art/export_cat.py
The review cushion, camera, lights and strand geometry are not exported.
"""
from pathlib import Path
import json

import bpy
from mathutils import Matrix, Vector

root = Path(__file__).resolve().parents[1]
cat = bpy.data.collections["Purrlock · cream cat"]
camera = bpy.data.objects["Reference three-quarter"]
mat = bpy.data.materials.new("Cat UV appearance assigned in Godot")
bpy.ops.object.select_all(action="DESELECT")

def rig_node(name, position):
    node = bpy.data.objects.new(name, None)
    bpy.context.scene.collection.objects.link(node)
    node.location = position
    node.select_set(True)
    return node

root_node = rig_node("CatRoot", (0, 0, 0))
# Turn about the buried rear of the head, not the muzzle or the paws.
head = rig_node("CatHead", (0, -.43, .64))
head.parent = root_node
bpy.context.view_layer.update()
for obj in cat.objects:
    if obj.type != "MESH":
        continue
    moving = obj.name.removeprefix("Cat • ").startswith(
        ("sculpted dome", "broad rooted", "eye", "set enamel", "fine visible", "sculpted triangular", "stitched smile"))
    matrix = obj.matrix_world.copy()
    obj.parent = head if moving else root_node
    obj.matrix_world = matrix
    uv = obj.data.uv_layers
    uv.active = uv["Locked pose color UV"]
    for layer in list(uv):
        if layer.name != "Locked pose color UV":
            uv.remove(layer)
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    # Film source has dense Boolean-sculpted body and tail. Keep curves and
    # facial geometry intact, reduce the smooth torso/tail for mobile WebGL.
    ratio = .034 if "torso" in obj.name else .085 if "tail" in obj.name else .36
    d = obj.modifiers.new("Game mesh reduction", "DECIMATE")
    d.ratio = ratio
    obj.select_set(True)
bpy.ops.export_scene.gltf(filepath=str(root/"assets"/"cat.glb"), export_format="GLB",
                         use_selection=True, export_apply=True, export_cameras=False,
                         export_lights=False, export_animations=False)

def gd(v):
    return "Vector3("+",".join(f"{x:.8f}" for x in (v.x,v.z,-v.y))+")"

cam_pos = camera.matrix_world.translation
look_dir = camera.matrix_world.to_quaternion() @ Vector((0, 0, -1))
(root/"game"/"cat_layout.gd").write_text(
    "extends RefCounted\n# Generated by art/export_cat.py from the fitted cat reference view.\n"
    "const TILE := Rect2(389,223,146,146)\n"
    f"const CAMERA := {gd(cam_pos)}\n"
    f"const LOOK := {gd(cam_pos+look_dir*8)}\n"
    f"const SIZE := {camera.data.ortho_scale:.8f}\n"
)
