"""Pack clean background plus six tea assets. Pillow required, OpenCV optional for CPU denoising."""
import argparse
from pathlib import Path
from PIL import Image, ImageFilter
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument("stage",type=Path)
p.add_argument("--already-denoised",action="store_true")
args=p.parse_args()
assets=ROOT/"assets"
keys=["saucer","cup","plate","fork","bowl","teapot"]
base=Image.open(args.stage/"room.png").convert("RGB")
if not args.already_denoised:
    try:
        import cv2
        import numpy as np
        rgb=np.asarray(base)
        # Keep intentional stitch/model edges; remove only Monte Carlo speckle.
        bgr=cv2.cvtColor(rgb,cv2.COLOR_RGB2BGR)
        clean=cv2.fastNlMeansDenoisingColored(bgr,None,4.0,3.4,7,17)
        base=Image.blend(base,Image.fromarray(cv2.cvtColor(clean,cv2.COLOR_BGR2RGB)),.88)
    except ImportError:
        base=Image.blend(base,base.filter(ImageFilter.MedianFilter(3)),.53)
base.save(assets/"room.webp",quality=94,method=6)
atlas=Image.new("RGBA",(704,448))
data={}
thumbs=args.stage/"thumbs"
thumbs.mkdir(exist_ok=True)
x,y,row=4,4,0
for key in keys:
    im=Image.open(args.stage/(key+".png")).convert("RGBA")
    alpha=im.getchannel("A")
    bounds=alpha.point(lambda p:255 if p>=5 else 0).getbbox()
    assert bounds is not None,key
    l,t,r,b=bounds
    l=max(0,l-2);t=max(0,t-2);r=min(im.width,r+2);b=min(im.height,b+2)
    part=im.crop((l,t,r,b))
    if x+part.width+4>atlas.width:
        x=4;y+=row+8;row=0
    assert y+part.height+4<=atlas.height,(key,part.size)
    atlas.paste(part,(x,y))
    sample=part.copy()
    sample.thumbnail((132,132),Image.Resampling.LANCZOS)
    tile=Image.new("RGBA",(144,144),(247,236,217,255))
    tile.alpha_composite(sample,((144-sample.width)//2,(144-sample.height)//2))
    tile.save(thumbs/(key+".png"))
    data[key]=(x,y,part.width,part.height,l,t)
    x+=part.width+8;row=max(row,part.height)
atlas=atlas.crop((0,0,atlas.width,y+row+4))
atlas.save(assets/"tea-sprites.webp",quality=97,method=6,exact=True)
lines=["extends RefCounted","# Generated by art/pack_tea.py. Atlas rect and placement on the fixed camera.","const FRAMES := {"]
for key,(x,y,w,h,l,t) in data.items():
    lines.append(f'\t"{key}":[Rect2({x},{y},{w},{h}),Vector2({l},{t})],')
lines.append("}")
(ROOT/"game"/"tea_frames.gd").write_text("\n".join(lines)+"\n")
for key,d in data.items():print(key,d)
