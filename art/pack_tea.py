"""Pack the room and its fixed-camera 2D sprite/animation atlas. Pillow required."""
import argparse
import json
from pathlib import Path

from PIL import Image,ImageFilter

ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument("stage",type=Path)
p.add_argument("--already-denoised",action="store_true")
args=p.parse_args()
assets=ROOT/"assets"
targets=("saucer","cup","plate","fork","bowl","teapot")
plants=("rubber_plant","lance_plant")
balloons=tuple(f"balloon_{i}" for i in range(3))
layout=json.loads((args.stage/"room-layout.json").read_text())
base=Image.open(args.stage/"room.png").convert("RGB")
def clean(im):
    if args.already_denoised:return im
    try:
        import cv2
        import numpy as np
        rgb=np.asarray(im)
        bgr=cv2.cvtColor(rgb,cv2.COLOR_RGB2BGR)
        soft=cv2.fastNlMeansDenoisingColored(bgr,None,3.4,3.2,7,17)
        return Image.blend(im,Image.fromarray(cv2.cvtColor(soft,cv2.COLOR_BGR2RGB)),.87)
    except ImportError:
        return Image.blend(im,im.filter(ImageFilter.MedianFilter(3)),.51)
base=clean(base)
base.save(assets/"room.webp",quality=94,method=6)
atlas=Image.new("RGBA",(768,1536))
data={}
thumbs=args.stage/"thumbs"
thumbs.mkdir(exist_ok=True)
clips={k:[f"{k}_{i:02d}" for i in range(17)] for k in plants}
x,y,row=3,3,0

def pack(key,group,fix_size=False,thumbnail=False):
    global x,y,row
    left,top,right,bottom=layout["bounds"][group]
    im=Image.open(args.stage/(key+".png")).convert("RGBA")
    expected=(right-left,bottom-top)
    if key=="fork":
        assert im.size==tuple(x*2 for x in expected)
        im=im.resize(expected,Image.Resampling.LANCZOS)
    assert im.size==expected,(key,im.size,layout["bounds"][group])
    if fix_size:
        part=im
    else:
        bounds=im.getchannel("A").point(lambda value:255 if value>=5 else 0).getbbox()
        assert bounds is not None,key
        l,t,r,b=bounds
        l=max(0,l-2);t=max(0,t-2);r=min(im.width,r+2);b=min(im.height,b+2)
        part=im.crop((l,t,r,b))
        left+=l;top+=t
    if x+part.width+3>atlas.width:
        x=3;y+=row+6;row=0
    assert y+part.height+3<=atlas.height,key
    atlas.paste(part,(x,y))
    data[key]=(x,y,part.width,part.height,left,top)
    x+=part.width+6;row=max(row,part.height)
    if thumbnail:
        sample=part.copy()
        sample.thumbnail((132,132),Image.Resampling.LANCZOS)
        tile=Image.new("RGBA",(144,144),(247,236,217,255))
        tile.alpha_composite(sample,((144-sample.width)//2,(144-sample.height)//2))
        tile.save(thumbs/(group+".png"))

for key in targets+balloons:pack(key,key,thumbnail=key in targets)
for key in plants:
    for i,frame in enumerate(clips[key]):pack(frame,key,fix_size=True,thumbnail=i==0)
atlas.crop((0,0,atlas.width,y+row+3)).save(assets/"tea-sprites.webp",quality=93,method=6,exact=True)
lines=["extends RefCounted","# Generated by art/pack_tea.py from the locked camera.","const FRAMES := {"]
for key,(x,y,w,h,l,t) in data.items():
    lines.append(f'\t"{key}": [Rect2({x},{y},{w},{h}),Vector2({l},{t})],')
lines.append("}")
lines.append("const CLIPS := "+json.dumps(clips,ensure_ascii=False))
lines.append("const MARKERS := {")
for key,(x,y) in layout["markers"].items():
    lines.append(f'\t"{key}": Vector2({x:.2f},{y:.2f}),')
lines.append("}")
(ROOT/"game"/"tea_frames.gd").write_text("\n".join(lines)+"\n")
