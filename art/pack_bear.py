"""Preserve the approved room's lighting while the teddy itself is rendered from 3D geometry."""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image,ImageFilter
try:
    import cv2
except ImportError:
    cv2=None

root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument("stage",type=Path)
p.add_argument("reference",type=Path,help="Original room image with the teddy in it")
args=p.parse_args()
layout=json.loads((args.stage/"bear-layout.json").read_text())
l,t,r,b=layout["bounds"]
w,h=r-l,b-t
reference=Image.open(args.reference).convert("RGB")
review=reference.crop((l,t,r,b))
clean=Image.open(args.stage/"bear-clear.png").convert("RGB")
assert review.size==clean.size==(w,h)
if cv2 is not None:
    pixels=np.asarray(clean)
    soft=cv2.fastNlMeansDenoisingColored(pixels,None,3.4,3.2,7,17)
    clean=Image.blend(clean,Image.fromarray(soft),.87)
else:
    clean=Image.blend(clean,clean.filter(ImageFilter.MedianFilter(3)),.51)
raw=Image.open(args.stage/"bear-coverage.png").getchannel("A")
assert raw.size==(w*2,h*2)
mask=raw.resize((w,h),Image.Resampling.LANCZOS)
# Replace the old silhouette and a narrow ring around it, not the rest of the room.
# Contact shadows were kept in the Cycles clean plate via camera ray visibility.
select=mask.point(lambda pixel:255 if pixel>1 else 0).filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(.72))
patch=Image.composite(clean,review,select)
reference.paste(patch,(l,t))
reference.save(root/"assets"/"room.webp",lossless=True,method=6)

# Texture colors right under the silhouette are uncomposited against the clean
# plate: the viewport, not a 2D sprite mask, supplies the actual final coverage.
B=np.asarray(patch,dtype=np.float32)
O=np.asarray(review,dtype=np.float32)
A=np.asarray(mask,dtype=np.float32)[:,:,None]/255
F=np.where(A>0,np.clip(B+(O-B)/np.maximum(A,.16),0,255),B)
Image.fromarray(np.uint8(np.round(F))).save(root/"assets"/"teddy-look.png",optimize=True)

def vec(name,kind="Vector3"):
    return kind+"("+",".join(map(str,layout[name]))+")"
(root/"game"/"teddy_layout.gd").write_text(
    "extends RefCounted\n# Generated by art/pack_bear.py from the room's camera.\n"
    f"const TILE := Rect2({l},{t},{w},{h})\n"
    f"const CAMERA := {vec('camera')}\nconst TARGET := {vec('target')}\n"
    f"const ORIGIN := {vec('origin')}\nconst ANCHOR := {vec('anchor_local')}\n"
    f"const SCREEN_PIN := {vec('screen_pin','Vector2')}\n"
    f"const LENS := {layout['lens']}\nconst SENSOR_WIDTH := {layout['sensor_width']}\n")
